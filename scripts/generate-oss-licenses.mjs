// 앱에 포함되는 오픈소스 목록(app/src/legal/oss-licenses.json)을 만들고 라이선스를 감사한다.
// Cutpick/scripts/generate-oss-licenses.mjs를 웹 앱용으로 고친 것: 번들 소스맵 대신 app/package.json의
// 런타임 dependencies를 시작점으로 의존성 트리(dependencies만, devDependencies 제외)를 따라간다.
// 사용: node scripts/generate-oss-licenses.mjs   (app 빌드 전에 자동 실행)
// 허용 목록 밖 라이선스가 있으면 exit 1 — 출시 전 검토(GPL/AGPL 발견 시 중단 후 보고).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const APP = join(ROOT, 'app');
const OUT = join(APP, 'src/legal/oss-licenses.json');
// 런타임에 import되지 않는 의존성(CLI 빌드 도구). SDK dist/index.js가 import하는 것은 @webview-bridge/web·semver·valibot뿐(3.9.0 확인).
const BUILD_ONLY = new Set(['@apps-in-toss/cli']);
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'Unlicense', 'CC0-1.0', 'BlueOak-1.0.0']);

/** Node 해석 규칙대로 from 디렉터리에서 위로 올라가며 node_modules/<name> 을 찾는다. */
function findPackage(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const p = join(dir, 'node_modules', name);
    if (existsSync(join(p, 'package.json'))) return p;
    if (dirname(dir) === dir) return null;
  }
}

function licenseOf(meta) {
  if (typeof meta.license === 'string') return meta.license;
  if (meta.license?.type) return meta.license.type;
  if (Array.isArray(meta.licenses)) return meta.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

function isAllowed(expr) {
  const e = expr.replace(/[()]/g, '').trim();
  if (e.includes(' OR ')) return e.split(' OR ').some((x) => isAllowed(x));
  return e.split(' AND ').every((x) => ALLOWED.has(x.trim()));
}

const COPYRIGHT_RE = /^\s*(copyright\b|\(c\)|©)/i;
const texts = new Map();
const packages = new Map();
const problems = [];

const appPkg = JSON.parse(readFileSync(join(APP, 'package.json'), 'utf8'));
const queue = Object.keys(appPkg.dependencies ?? {}).map((name) => ({ name, from: APP }));
while (queue.length) {
  const { name, from } = queue.shift();
  if (BUILD_ONLY.has(name)) continue;
  const dir = findPackage(name, from);
  if (!dir) continue; // optional 의존성 등 설치 안 된 패키지
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const key = `${meta.name}@${meta.version}`;
  if (packages.has(key)) continue;
  const license = licenseOf(meta);
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(f));
  let copyright = [];
  let textId = null;
  if (file) {
    const lines = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim().split('\n');
    copyright = Array.from(new Set(lines.filter((l) => COPYRIGHT_RE.test(l)).map((l) => l.trim()))).slice(0, 4);
    const body = lines.filter((l) => !COPYRIGHT_RE.test(l)).join('\n').replace(/\n{3,}/g, '\n\n').trim();
    textId = createHash('sha1').update(body).digest('hex').slice(0, 10);
    if (!texts.has(textId)) texts.set(textId, body);
  }
  if (!copyright.length) {
    const author = typeof meta.author === 'string' ? meta.author.replace(/\s*<.*$/, '') : meta.author?.name;
    if (author) copyright = [`Copyright (c) ${author}`];
  }
  if (!isAllowed(license)) problems.push(`${key}: ${license}`);
  packages.set(key, { name: meta.name, version: meta.version, license, copyright, textId });
  for (const dep of Object.keys(meta.dependencies ?? {})) queue.push({ name: dep, from: dir });
}

const list = Array.from(packages.values()).sort((a, b) => a.name.localeCompare(b.name));
const used = new Set(list.map((p) => p.textId).filter(Boolean));
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `${JSON.stringify({ note: 'Generated by scripts/generate-oss-licenses.mjs — do not edit by hand.', packages: list, texts: Object.fromEntries(Array.from(texts).filter(([id]) => used.has(id))) }, null, 1)}\n`,
);

const counts = {};
for (const p of list) counts[p.license] = (counts[p.license] ?? 0) + 1;
console.log(`${list.length} runtime packages → ${OUT}`, counts);
if (problems.length) {
  console.error(`review needed:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
